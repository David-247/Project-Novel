import { getSchema } from '@tiptap/core'
import { describe, expect, it } from 'vitest'
import { countManuscript, createEditorExtensions } from '@/features/editor'
import { countText } from '@/shared/text'
import { buildManuscript } from './build'
import { FEATURE_FIXTURE_DOC, FEATURE_FIXTURE_FOOTNOTES, FEATURE_FIXTURE_STYLES } from './fixtures'
import { manuscriptPlainText, runsText } from './plain-text'
import type { ManuscriptBlock, ManuscriptIR } from './types'

// Word-count parity (Wave 1 integration): the text an export contains (the IR) counts the same as the
// live word count (docs/word-count.md: "the text as it reads with every pending tracked change accepted").
// List markers are generated by the renderer (Word does not count list numbers), so they are left out.
const schema = getSchema(createEditorExtensions())

function irBodyWords(ir: ManuscriptIR): number {
  let words = 0
  const blocks = (list: readonly ManuscriptBlock[]) => {
    for (const b of list) if (b.kind === 'paragraph') words += countText(runsText(b.runs)).words
  }
  blocks(ir.frontMatter)
  for (const c of ir.chapters) {
    words += countText(runsText(c.number)).words + countText(runsText(c.title)).words
    blocks(c.blocks)
  }
  return words
}

describe('IR / word-count parity on the feature fixture', () => {
  const ir = buildManuscript(FEATURE_FIXTURE_DOC, FEATURE_FIXTURE_STYLES, { footnotes: FEATURE_FIXTURE_FOOTNOTES })
  const live = countManuscript(schema.nodeFromJSON(FEATURE_FIXTURE_DOC))

  it('body words: the IR text counts the same as countManuscript', () => {
    expect(irBodyWords(ir)).toBe(live.body.words)
  })

  it('footnote words: the IR footnotes count the same as countManuscript', () => {
    const words = ir.footnotes.reduce((n, f) => n + countText(runsText(f.runs)).words, 0)
    expect(words).toBe(live.footnotes.words)
  })

  it('manuscriptPlainText adds only the generated numbered-list markers ("3.", "4.") on top', () => {
    const numbered = [...ir.frontMatter, ...ir.chapters.flatMap((c) => c.blocks)].filter(
      (b) => b.kind === 'paragraph' && b.list?.marker && countText(b.list.marker).words > 0,
    ).length
    expect(countText(manuscriptPlainText(ir)).words).toBe(live.body.words + numbered)
  })
})
