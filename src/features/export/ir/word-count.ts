import { countText } from '@/shared/text'
// Leaf modules only (not './index'): the DOCX export worker imports this, and must not load the editor.
import { runsText } from './plain-text'
import type { ManuscriptBlock, ManuscriptIR } from './types'

export interface ManuscriptWordCount {
  /** The text: front matter, chapter numbers and titles, and every paragraph (list markers left out). */
  body: number
  footnotes: number
  /** `body + footnotes`: Word's count with "Include textboxes, footnotes and endnotes" (the default). */
  total: number
}

/**
 * The manuscript's word count, from the IR's runs with the app's counting rules (docs/word-count.md).
 * It equals `countManuscript` on the same document (word-count parity): the IR text is the text with
 * pending changes accepted. List markers and scene-break markers are generated by the renderer and
 * are not counted (Word does not count list numbers), which is why this does not count
 * `manuscriptPlainText`.
 *
 * Neither generator counts: the wizard counts once (`titlePageWordCount`: `total` when Word Count's
 * "Include footnotes" is on, else `body`) and both title pages state that one number.
 */
export function manuscriptWordCount(ir: ManuscriptIR): ManuscriptWordCount {
  let body = 0
  const blocks = (list: readonly ManuscriptBlock[]) => {
    for (const b of list) if (b.kind === 'paragraph') body += countText(runsText(b.runs)).words
  }
  blocks(ir.frontMatter)
  for (const c of ir.chapters) {
    body += countText(runsText(c.number)).words + countText(runsText(c.title)).words
    blocks(c.blocks)
  }
  const footnotes = ir.footnotes.reduce((n, f) => n + countText(runsText(f.runs)).words, 0)
  return { body, footnotes, total: body + footnotes }
}
